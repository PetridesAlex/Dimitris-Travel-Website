type CityOpts = {
  id: string;
  countryId: string;
  continentSlug: string;
  countrySlug: string;
  slug: string;
  name: string;
  tagline: string;
  overview: string;
  image: string;
  featured?: boolean;
  currency?: string;
  languages?: string;
  timezone?: string;
  highlights?: string[];
};

function city(opts: CityOpts): CityDestination {
  return {
    id: opts.id,
    type: 'city',
    parentId: opts.countryId,
    slug: opts.slug,
    slugPath: `${opts.continentSlug}/${opts.countrySlug}/${opts.slug}`,
    name: opts.name,
    tagline: opts.tagline,
    overview: opts.overview,
    image: opts.image,
    featured: opts.featured ?? true,
    bestTimeToVisit: 'Seasonal — ask our designers',
    currency: opts.currency ?? 'Local currency',
    languages: opts.languages ?? 'Local languages',
    timezone: opts.timezone ?? 'Local time',
    visaInfo: 'As parent country.',
    weather: 'Regional climate variations apply.',
    highlights: opts.highlights ?? [],
  };
}

